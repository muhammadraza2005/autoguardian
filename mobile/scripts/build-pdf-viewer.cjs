/* global __dirname */
// Bundle only public PDF.js code, never documents. Run after updating PDF.js.
const {build}=require('esbuild');const fs=require('node:fs/promises');const path=require('node:path');
async function main(){
  const result=await build({stdin:{contents:`import * as pdf from 'pdfjs-dist/legacy/build/pdf.mjs';
    import * as worker from 'pdfjs-dist/legacy/build/pdf.worker.mjs';
    globalThis.agPdf=pdf;globalThis.pdfjsWorker=worker;`,resolveDir:path.resolve(__dirname,'..')},
    bundle:true,write:false,format:'iife',platform:'browser',target:'es2020',minify:true,legalComments:'inline'});
  const code=result.outputFiles[0].text;
  await fs.writeFile(path.resolve(__dirname,'../src/features/enrollment/pdfRenderer.generated.ts'),
    '// Generated by scripts/build-pdf-viewer.cjs from pinned PDF.js (Apache-2.0). Do not edit.\nexport const pdfRenderer = '+JSON.stringify(code)+';\n');
  console.log('Generated offline PDF renderer ('+code.length+' bytes of public code).');
}
main().catch(()=>{console.error('PDF renderer generation failed.');process.exitCode=1;});
